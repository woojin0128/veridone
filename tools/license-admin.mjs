#!/usr/bin/env node
// Veridone — vendor-side license administration. Zero dependencies.
//
//   node tools/license-admin.mjs init                 create the signing key pair (once) and embed the public key
//   node tools/license-admin.mjs issue --email a@b.com [--plan pro|team|enterprise] [--seats 5] [--days 365 | --exp 2027-12-31] [--org "Acme"] [--note "order #123"]
//   node tools/license-admin.mjs verify <key>         check a key against the embedded public key
//   node tools/license-admin.mjs list                 show issued keys (from the local ledger)
//   node tools/license-admin.mjs pubkey               print the embedded public key
//
// The PRIVATE key lives outside the repository (default ~/.veridone-vendor/, override with
// VERIDONE_VENDOR_DIR). Never commit it, never ship it: anyone holding it can mint licenses.

import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const KEY_MODULE = path.join(ROOT, 'scripts', 'lib', 'license-key.mjs');
const VENDOR_DIR = process.env.VERIDONE_VENDOR_DIR || path.join(os.homedir(), '.veridone-vendor');
const PRIVATE_KEY = path.join(VENDOR_DIR, 'license-signing-key.pem');
const LEDGER = path.join(VENDOR_DIR, 'issued.jsonl');

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const [k, inline] = a.slice(2).split(/=(.*)/s);
      if (inline !== undefined) args[k] = inline;
      else if (argv[i + 1] !== undefined && !argv[i + 1].startsWith('--')) args[k] = argv[++i];
      else args[k] = true;
    } else args._.push(a);
  }
  return args;
}

function die(msg) {
  process.stderr.write(`license-admin: ${msg}\n`);
  process.exit(1);
}

async function lib() {
  return import(path.join(ROOT, 'scripts', 'lib', 'license.mjs'));
}

function embeddedPublicKey() {
  const src = fs.readFileSync(KEY_MODULE, 'utf8');
  const m = /`(-----BEGIN PUBLIC KEY-----[\s\S]*?-----END PUBLIC KEY-----)`/.exec(src);
  return m ? m[1] : null;
}

function writePublicKeyModule(pem) {
  const body = `// Vendor public key used to verify Veridone license keys (Ed25519).
// Generated by \`node tools/license-admin.mjs init\`. Safe to publish: it can only
// verify signatures. The matching private key must never be committed or shipped.
export const LICENSE_PUBLIC_KEY_PEM = \`${pem.trim()}\`;
`;
  fs.writeFileSync(KEY_MODULE, body);
}

async function cmdInit(args) {
  fs.mkdirSync(VENDOR_DIR, { recursive: true, mode: 0o700 });
  if (fs.existsSync(PRIVATE_KEY) && !args.force) {
    const priv = crypto.createPrivateKey(fs.readFileSync(PRIVATE_KEY, 'utf8'));
    const pub = crypto.createPublicKey(priv).export({ type: 'spki', format: 'pem' }).toString();
    const current = embeddedPublicKey();
    if (current && current.trim() === pub.trim()) {
      console.log(`Already initialized. Signing key: ${PRIVATE_KEY}\nThe embedded public key matches it.`);
      return;
    }
    writePublicKeyModule(pub);
    console.log(`Re-embedded the public key for the existing signing key at ${PRIVATE_KEY}.`);
    return;
  }
  if (fs.existsSync(PRIVATE_KEY) && args.force) {
    const backup = `${PRIVATE_KEY}.${Date.now()}.bak`;
    fs.copyFileSync(PRIVATE_KEY, backup);
    console.log(`Backed up the previous signing key to ${backup}. Keys issued with it will stop validating in new builds.`);
  }
  const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
  fs.writeFileSync(PRIVATE_KEY, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
  writePublicKeyModule(publicKey.export({ type: 'spki', format: 'pem' }).toString());
  console.log(`Created the license signing key: ${PRIVATE_KEY} (mode 600)
Embedded the public key in ${path.relative(process.cwd(), KEY_MODULE) || KEY_MODULE}.

Next:
  1. Back up ${PRIVATE_KEY} somewhere safe (password manager / encrypted drive). Losing it means
     you cannot issue keys that existing builds accept; leaking it means anyone can.
  2. Commit scripts/lib/license-key.mjs (public key only) and publish a release.
  3. Issue a key:  node tools/license-admin.mjs issue --email buyer@example.com --plan pro --days 365`);
}

async function cmdIssue(args) {
  if (!fs.existsSync(PRIVATE_KEY)) die(`no signing key at ${PRIVATE_KEY}. Run: node tools/license-admin.mjs init`);
  const email = typeof args.email === 'string' ? args.email.trim() : '';
  const org = typeof args.org === 'string' ? args.org.trim() : '';
  if (!email && !org) die('pass --email (and/or --org)');
  if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) die(`invalid email: ${email}`);
  const plan = typeof args.plan === 'string' ? args.plan : 'pro';
  const { PLANS, signLicense, verifyLicense } = await lib();
  if (!PLANS[plan] || plan === 'free') die(`--plan must be one of ${Object.keys(PLANS).filter((p) => p !== 'free').join(', ')}`);
  const seats = Math.max(1, Number(args.seats) || 1);
  let exp = null;
  if (typeof args.exp === 'string') {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(args.exp) || Number.isNaN(Date.parse(args.exp))) die('--exp must be YYYY-MM-DD');
    exp = args.exp;
  } else if (args.days !== undefined && args.days !== 'never') {
    const days = Number(args.days);
    if (!Number.isFinite(days) || days <= 0) die('--days must be a positive number (or "never")');
    exp = new Date(Date.now() + days * 86400e3).toISOString().slice(0, 10);
  } else if (args.days === undefined) {
    exp = new Date(Date.now() + 365 * 86400e3).toISOString().slice(0, 10);
  }
  const id = typeof args.id === 'string' ? args.id : `lic_${crypto.randomBytes(8).toString('hex')}`;
  const payload = { id, plan, seats, iat: new Date().toISOString().slice(0, 10) };
  if (email) payload.email = email;
  if (org) payload.org = org;
  if (exp) payload.exp = exp;
  const key = signLicense(payload, fs.readFileSync(PRIVATE_KEY, 'utf8'));
  const pub = embeddedPublicKey();
  const check = verifyLicense(key, pub);
  if (!check.valid) die(`the embedded public key does not accept this key (${check.reason}). Run init to re-embed it, then rebuild.`);
  fs.mkdirSync(VENDOR_DIR, { recursive: true, mode: 0o700 });
  fs.appendFileSync(LEDGER, JSON.stringify({ ...payload, note: typeof args.note === 'string' ? args.note : undefined, issuedAt: new Date().toISOString(), keyTail: key.slice(-10) }) + '\n', { mode: 0o600 });
  if (args.json) console.log(JSON.stringify({ key, payload }, null, 2));
  else {
    console.log(key);
    process.stderr.write(`\nIssued ${plan} (${seats} seat${seats > 1 ? 's' : ''}) to ${email || org}, expires ${exp || 'never'}, id ${id}.\nThe buyer activates it with:  /veridone:license activate <key>   (or VERIDONE_LICENSE_KEY=<key> in CI)\n`);
  }
}

async function cmdVerify(args) {
  const key = args._[1];
  if (!key) die('usage: verify <key>');
  const { verifyLicense } = await lib();
  const r = verifyLicense(key, embeddedPublicKey());
  console.log(JSON.stringify(r, null, 2));
  process.exitCode = r.valid ? 0 : 1;
}

function cmdList() {
  let rows = [];
  try { rows = fs.readFileSync(LEDGER, 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l)); } catch { /* none */ }
  if (!rows.length) { console.log(`No keys issued yet (ledger: ${LEDGER}).`); return; }
  for (const r of rows) console.log(`${r.issuedAt.slice(0, 10)}  ${r.id}  ${String(r.plan).padEnd(10)} seats ${String(r.seats).padEnd(3)} exp ${String(r.exp || 'never').padEnd(10)}  ${r.email || r.org}${r.note ? `  (${r.note})` : ''}`);
}

const args = parseArgs(process.argv.slice(2));
const cmd = args._[0];
const table = { init: cmdInit, issue: cmdIssue, verify: cmdVerify, list: cmdList, pubkey: () => console.log(embeddedPublicKey() || '(none)') };
if (!table[cmd]) {
  console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 12).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
  process.exit(cmd ? 2 : 0);
}
await table[cmd](args);
