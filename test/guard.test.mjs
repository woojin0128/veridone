describe('uncommitted work is protected', () => {
  test('git reset --hard, checkout ., clean and rm of dirty paths ask first', async () => {
    const dirty = gitRepo({ 'src/a.js': 'a\n', 'src/b.js': 'b\n' });
    fs.writeFileSync(path.join(dirty, 'src/a.js'), 'changed\n');
    fs.writeFileSync(path.join(dirty, 'src/new.js'), 'untracked\n');
    const ctx = async () => makeContext({ cwd: dirty, projectRoot: dirty, config: await config('standard') });
    for (const [cmd, rule] of [
      ['git reset --hard', 'git-discard-changes'],
      ['git checkout -- .', 'git-discard-changes'],
      ['git restore .', 'git-discard-changes'],
      ['git clean -fd', 'git-discard-changes'],
      ['git stash drop', 'git-discard-changes'],
      ['rm -rf src', 'rm-uncommitted-work'],
    ]) {
      const r = analyzeBash(cmd, await ctx());
      assert.equal(r.level, 'ask', `${cmd}: ${JSON.stringify(r.findings)}`);
      assert.ok(rules(r).includes(rule), `${cmd}: ${rules(r)}`);
    }
  });
});

describe('modes and configuration', () => {
  test('relaxed mode downgrades confirmations but never catastrophic denies', async () => {
    assert.equal((await check('rm tests/app.test.js', 'relaxed')).level, 'warn');
    assert.equal((await check('rm -rf /', 'relaxed')).level, 'deny');
  });
  test('strict mode denies force-pushes to protected branches', async () => {
    assert.equal((await check('git push --force origin main', 'strict')).level, 'deny');
  });
  test('off mode does nothing', async () => {
    assert.equal((await check('rm -rf /', 'off')).level, null);
  });
  test('per-rule overrides and allowCommands apply', async () => {
    const ctx = makeContext({ cwd: repo, projectRoot: repo, config: await config('standard', { guard: { rules: { 'publish-release': 'off' }, allowCommands: ['^terraform destroy -target=module\\.scratch'] } }) });
    assert.equal(analyzeBash('npm publish', ctx).level, null);
    assert.equal(analyzeBash('terraform destroy -target=module.scratch', ctx).level, null);
    assert.equal(analyzeBash('terraform destroy', ctx).level, 'ask');
  });
});

describe('file tools', () => {
  const ctx = async (mode = 'standard') => makeContext({ cwd: repo, projectRoot: repo, config: await config(mode) });
  test('editing .git internals is denied', async () => {
    const r = analyzeFileWrite({ tool: 'Write', filePath: '.git/config', newText: '[core]' }, await ctx());
    assert.equal(r.level, 'deny');
  });
  test('lockfiles and guardrail files ask', async () => {
    assert.equal(analyzeFileWrite({ tool: 'Edit', filePath: 'package-lock.json', newText: '{}' }, await ctx()).level, 'ask');
    const g = analyzeFileWrite({ tool: 'Write', filePath: '.claude/settings.json', newText: '{}' }, await ctx());
    assert.ok(rules(g).includes('guardrail-tamper'));
  });
  test('generated files and committed migrations ask', async () => {
    assert.ok(rules(analyzeFileWrite({ tool: 'Edit', filePath: 'gen/api.ts', newText: 'x' }, await ctx())).includes('generated-file'));
    assert.ok(rules(analyzeFileWrite({ tool: 'Edit', filePath: 'db/migrations/001_init.sql', newText: 'x' }, await ctx())).includes('migration-edit'));
  });
  test('hard-coded live credentials are denied, placeholders are fine', async () => {
    const live = 'const stripe = new Stripe("sk_live_' + 'a1B2c3D4e5F6g7H8i9J0k1L2m3N4");\n';
    assert.equal(analyzeFileWrite({ tool: 'Write', filePath: 'src/pay.js', newText: live }, await ctx()).level, 'deny');
    const fake = 'const key = process.env.STRIPE_KEY || "sk_live_your_key_here";\n';
    assert.equal(analyzeFileWrite({ tool: 'Write', filePath: 'src/pay.js', newText: fake }, await ctx()).level, null);
  });
  test('secrets written to a git-ignored .env are allowed', async () => {
    const r = analyzeFileWrite({ tool: 'Write', filePath: '.env', newText: 'GITHUB_TOKEN=ghp_' + 'aB3dE5fG7hJ9kL1mN3pQ5rS7tU9vW1xY3zA5b\n' }, await ctx());
    assert.equal(r.level, null, JSON.stringify(r.findings));
  });
  test('reading secret files asks; examples and ordinary files do not', async () => {
    assert.equal(analyzeFileRead('.env', await ctx()).level, 'ask');
    assert.equal(analyzeFileRead(path.join(process.env.HOME || '/root', '.aws/credentials'), await ctx()).level, 'ask');
    assert.equal(analyzeFileRead('.env.example', await ctx()).level, null);
    assert.equal(analyzeFileRead('src/app.js', await ctx()).level, null);
  });
});

