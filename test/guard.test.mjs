describe('team command rules (Pro)', () => {
  test('match the whole command line with the configured level', async () => {
    const cfg = await config('standard', { guard: { customRules: [
      { id: 'prod-db', pattern: 'psql\\s+.*prod', level: 'deny', message: 'Never touch the production database from an agent.' },
      { id: 'deploy', pattern: '^make deploy', level: 'ask', message: 'Deploys need a human.' },
    ] } });
    const ctx = () => makeContext({ cwd: repo, projectRoot: repo, config: cfg });
    const d = analyzeBash('psql -h prod.db.internal -c "select 1"', ctx());
    assert.equal(d.level, 'deny');
    assert.equal(d.findings[0].rule, 'custom:prod-db');
    assert.equal(analyzeBash('make deploy ENV=staging', ctx()).level, 'ask');
    assert.equal(analyzeBash('make test', ctx()).level, null);
  });
  test('entitlements strip custom rules without a license', async () => {
    const { applyEntitlements, usesCustomRules } = await import('../scripts/lib/config.mjs');
    const cfg = await config('standard', { guard: { customRules: [{ id: 'x', pattern: 'x' }] } });
    assert.equal(usesCustomRules(cfg), true);
    assert.match(applyEntitlements(cfg, false), /need a Veridone Pro or Team license/);
    assert.equal(usesCustomRules(cfg), false);
    const licensed = await config('standard', { integrity: { customRules: [{ id: 'y', pattern: 'y' }] } });
    assert.equal(applyEntitlements(licensed, true), null);
    assert.equal(licensed.integrity.customRules.length, 1);
  });
});

test('reading only variable names from a secrets file is allowed', async () => {
  for (const cmd of ['grep -o "^[A-Z_]*=" .env', "grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' .env", 'grep -c API .env', 'grep -q KEY .env', 'cut -d= -f1 .env', "awk -F= '{print $1}' .env", "sed 's/=.*//' .env"]) {
    assert.equal((await check(cmd)).level, null, cmd);
  }
  for (const cmd of ['grep -o "API_KEY=.*" .env', 'grep -o "^.*=" .env', 'grep API .env', 'cut -d= -f2 .env', "awk -F= '{print $2}' .env"]) {
    assert.equal((await check(cmd)).level, 'ask', cmd);
  }
});

test('the agent cannot quietly loosen Veridone through its own CLI', async () => {
  assert.equal((await check('node "/x/plugins/cache/veridone/veridone/1.0.0/scripts/veridone.mjs" mode off --session s1')).level, 'ask');
  assert.equal((await check('node scripts/veridone.mjs mode relaxed --project')).level, 'ask');
  assert.equal((await check('node scripts/veridone.mjs license deactivate')).level, 'ask');
  assert.equal((await check('node scripts/veridone.mjs mode strict')).level, null);
  assert.equal((await check('node scripts/veridone.mjs status')).level, null);
});

test('protectedFiles also cover writes, moves and deletes made through the shell', async () => {
  const cfg = await config('standard', { guard: { protectedFiles: { deny: ['infra/prod/**'], ask: ['src/payments/**'] } } });
  const ctx = () => makeContext({ cwd: repo, projectRoot: repo, config: cfg });
  for (const cmd of ["sed -i 's/a/b/' infra/prod/main.tf", 'echo x > infra/prod/vars.tf', 'cp /tmp/x infra/prod/main.tf', 'rm infra/prod/main.tf', 'mv infra/prod/main.tf /tmp/']) {
    assert.equal(analyzeBash(cmd, ctx()).level, 'deny', cmd);
  }
  assert.equal(analyzeBash('echo x >> src/payments/charge.js', ctx()).level, 'ask');
  assert.equal(analyzeBash('rm src/payments/old.js', ctx()).level, null, 'deletes honor only the deny list');
  assert.equal(analyzeBash('echo x > src/other.js', ctx()).level, null);
});
